# SLICING EXAMPLE
name = "Bhumika"
print("Original name:", name)
print("First 3 letters:", name[0:3])
print("Last 3 letters:", name[-3:])

# COMPARISON OPERATORS
a = 10
b = 20

print("\nComparison Operators:")
print("a == b:", a == b)
print("a != b:", a != b)
print("a > b:", a > b)
print("a < b:", a < b)

# LOGICAL OPERATORS
x = 5

print("\nLogical Operators:")
print("x > 2 and x < 10:", x > 2 and x < 10)
print("x > 10 or x < 10:", x > 10 or x < 10)
print("not(x > 2):", not(x > 2))
