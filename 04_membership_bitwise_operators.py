# Bitwise Operators Example

a = 5   # Binary: 0101
b = 3   # Binary: 0011

print("AND (&):", a & b)   # 1
print("OR (|):", a | b)    # 7
print("XOR (^):", a ^ b)   # 6
print("NOT (~a):", ~a)     # -6

# Shift Operators
print("Left Shift (a << 1):", a << 1)   # 10
print("Right Shift (a >> 1):", a >> 1)  # 2
