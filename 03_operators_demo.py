# Bitwise Operators Example

a = 5   # Binary: 0101
b = 3   # Binary: 0011

print("AND (&):", a & b)   # 1
print("OR (|):", a | b)    # 7
print("XOR (^):", a ^ b)   # 6
print("NOT (~a):", ~a)     # -6

# Shift Operators
print("Left Shift (a << 1):", a << 1)   # 10
print("Right Shift (a >> 1):", a >> 1)  # 2# SLICING EXAMPLE
name = "Bhumika"
print("Original name:", name)
print("First 3 letters:", name[0:3])
print("Last 3 letters:", name[-3:])

# COMPARISON OPERATORS
a = 10
b = 20

print("\nComparison Operators:")
print("a == b:", a == b)
print("a != b:", a != b)
print("a > b:", a > b)
print("a < b:", a < b)

# LOGICAL OPERATORS
x = 5

print("\nLogical Operators:")
print("x > 2 and x < 10:", x > 2 and x < 10)
print("x > 10 or x < 10:", x > 10 or x < 10)
print("not(x > 2):", not(x > 2))
